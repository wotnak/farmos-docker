import { test, expect } from '@playwright/test';
import { login, uniqueName, createAsset, fillEntityBasics, saveEntity, openTab, selectAutocomplete } from '../../support/farmos.js';
import { apiRecord, createLocation, moveTo, harvest, assertViewerAccess, exportAsset } from '../../support/production-contrib.js';
import { rememberRecord } from '../../support/contrib.js';

test('fungi require a species and preserve substrate, lineage, location, harvest and archive changes', async ({ page, browser }) => {
  await login(page);
  const species = uniqueName('Pleurotus ostreatus');
  const substrate = uniqueName('Pasteurized straw');
  const mother = await createAsset(page, { type: 'fungi', name: uniqueName('Mother culture'), configure: async () => {
    await page.getByLabel('Fungi species/variety', { exact: true }).fill(species);
  } });
  const name = uniqueName('Oyster mushroom batch');
  await page.goto('/asset/add/fungi');
  await fillEntityBasics(page, { name });
  await page.locator('form.asset-form').evaluate(form => { form.noValidate = true; });
  await page.locator('#gin-sticky-edit-submit').click();
  await expect(page.getByRole('contentinfo', { name: 'Error message' })).toContainText('Fungi species/variety field is required');
  await expect(page).toHaveURL(/\/asset\/add\/fungi$/);
  await selectAutocomplete(page, 'fungi_type[0][target_id]', species);
  await page.getByLabel('Substrate type', { exact: true }).fill(substrate);
  await openTab(page, 'Parents');
  await selectAutocomplete(page, 'parent[0][target_id]', mother.name);
  const batch = { ...await saveEntity(page), name };
  await expect(page.getByText(substrate, { exact: true })).toBeVisible();
  const room = await createLocation(page, uniqueName('Fruiting area'));
  await moveTo(page, batch, room);
  await page.goto(`/log/add/activity?asset=${batch.id}`);
  const inoculationName = uniqueName('Mushroom inoculation');
  await fillEntityBasics(page, { name: inoculationName, notes: 'Inoculated pasteurized substrate from the mother culture.' });
  const inoculation = await saveEntity(page, 'log');
  const crop = await harvest(page, batch, uniqueName('Oyster mushroom harvest'), '4.75', 'kg');
  const { included: cropIncluded } = await apiRecord(page, 'log', 'harvest', crop.name, 'quantity');
  const quantity = cropIncluded.find(item => item.type === 'quantity--standard');
  expect(Number(quantity.attributes.value.decimal)).toBe(4.75);
  const revisedSubstrate = uniqueName('Supplemented straw');
  await page.goto(`${batch.path}/edit`);
  await page.getByLabel('Substrate type', { exact: true }).fill(revisedSubstrate);
  await fillEntityBasics(page, { notes: 'Second flush completed.' });
  await saveEntity(page);
  await expect(page.getByText(revisedSubstrate, { exact: true })).toBeVisible();
  const { record, included } = await apiRecord(page, 'asset', 'fungi', name, 'fungi_type,substrate_type,parent,location');
  const reference = field => included.find(item => item.id === (Array.isArray(record.relationships[field].data) ? record.relationships[field].data[0].id : record.relationships[field].data.id));
  expect(reference('fungi_type').attributes.name).toBe(species);
  expect(reference('substrate_type').attributes.name).toBe(revisedSubstrate);
  expect(reference('parent').attributes.name).toBe(mother.name);
  expect(reference('location').attributes.name).toBe(room.name);
  await exportAsset(page, batch, [species, revisedSubstrate]);
  await assertViewerAccess(page, browser, batch, 'fungi');
  await page.goto(`${batch.path}/edit`);
  await page.locator('[name="archived[value]"]').check();
  await saveEntity(page);
  expect((await apiRecord(page, 'asset', 'fungi', name)).record.attributes.archived).toBe(true);
  rememberRecord('fungi', { path: batch.path, name, apiPath: `/api/asset/fungi/${record.id}`, attributes: { archived: true },
    relationships: { fungi_type: reference('fungi_type').id, substrate_type: reference('substrate_type').id, parent: reference('parent').id, location: reference('location').id } });
  rememberRecord('fungi', { path: inoculation.path, name: inoculationName });
  rememberRecord('fungi', { path: crop.path, name: crop.name });
  rememberRecord('fungi', { path: crop.path, name: crop.name, apiPath: `/api/quantity/standard/${quantity.id}`, attributes: { measure: 'weight', value: quantity.attributes.value } });
});
